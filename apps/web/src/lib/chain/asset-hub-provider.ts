/**
 * Asset Hub Provider
 *
 * Provides WebSocket RPC connection to Asset Hub with singleton pattern
 * and fingerprint caching. Supports Revive EVM contract interactions.
 *
 * Pattern adapted from p2p-market reference implementation.
 */

import { createClient, type PolkadotClient, type TypedApi } from 'polkadot-api';
import { getWsProvider } from 'polkadot-api/ws';
import { assetHub } from '@polkadot-api/descriptors';
import { CHAIN_CONFIG } from './config';
import { createLogger } from '../logging';

const logger = createLogger('AssetHubProvider');

// ============================================================
// Types
// ============================================================

/** The typed Asset Hub API generated by the papi CLI (`tx.Revive.*`, `apis.ReviveApi.*`). */
export type AssetHubApi = TypedApi<typeof assetHub>;

export interface AssetHubConnection {
  readonly client: PolkadotClient;
  /** Typed Asset Hub API bound to the generated descriptors (Revive pallet + runtime API). */
  readonly api: AssetHubApi;
  readonly chainId: number;
  readonly nativeDecimals: number;
  readonly evmDecimals: number;
  /**
   * Conversion factor between native planck (10 decimals) and EVM wei (18
   * decimals), read from `Revive.NativeToEthRatio` runtime constant. On Paseo
   * this is 1e8 (18 − 10 = 8 digit difference). Used to convert an EVM-18-decimal
   * contract amount into the native-planck value carried by the `Revive.call`
   * extrinsic (see {@link nativeFromEvmBalance}).
   */
  readonly nativeToEvmRatio: bigint;
}

export type Unsubscribe = () => void;

// ============================================================
// State
// ============================================================

/** Cached connection promise to prevent race conditions */
let connectionPromise: Promise<AssetHubConnection> | null = null;

/** Active WebSocket provider for cleanup */
let wsProvider: ReturnType<typeof getWsProvider> | null = null;

/** Native to EVM decimal ratio (for Revive) */
const NATIVE_DECIMALS = 10;
const EVM_DECIMALS = 18;

/**
 * Fallback NativeToEthRatio when the runtime constant cannot be read. This is
 * the proven Paseo Asset Hub value: 10^(18 − 10) = 1e8. Kept as a documented
 * fail-closed fallback mirroring the p2p-market reference.
 */
const DEFAULT_NATIVE_TO_EVM_RATIO = 100_000_000n; // 1e8

// ============================================================
// Connection Management
// ============================================================

/**
 * Get or create the Asset Hub client connection.
 *
 * Uses singleton pattern with fingerprint caching to ensure
 * only one WebSocket connection is established.
 *
 * @returns Promise resolving to the Asset Hub connection
 */
export async function getAssetHubClient(): Promise<AssetHubConnection> {
  if (connectionPromise) {
    return connectionPromise;
  }

  connectionPromise = createConnection();
  return connectionPromise;
}

/**
 * Create a new connection to Asset Hub.
 */
async function createConnection(): Promise<AssetHubConnection> {
  const { rpc, chainId } = CHAIN_CONFIG.assetHub;

  logger.info('Connecting to Asset Hub', 'createConnection', { rpc, chainId });

  try {
    // Create WebSocket provider
    wsProvider = getWsProvider(rpc);

    // Create Polkadot client
    const client = createClient(wsProvider);

    // Bind the generated Asset Hub descriptors to get the typed API surface
    // (Revive pallet + ReviveApi runtime API). Both the client and the
    // descriptors are polkadot-api 2.x, so this is a clean same-major boundary.
    const api = client.getTypedApi(assetHub);

    // Wait for connection to be established
    const chainSpec = await client.getChainSpecData();

    logger.info('Connected to Asset Hub', 'createConnection', {
      chainName: chainSpec.name,
      chainId,
    });

    // Read NativeToEthRatio from the Revive pallet runtime constants. This is
    // the conversion factor between native planck and EVM wei (1e8 on Paseo).
    // Mirrors the p2p-market reference; falls back to the proven Paseo value.
    let nativeToEvmRatio = DEFAULT_NATIVE_TO_EVM_RATIO;
    try {
      nativeToEvmRatio = BigInt(await api.constants.Revive.NativeToEthRatio());
    } catch (error) {
      logger.warn(
        'Failed to read Revive.NativeToEthRatio; falling back to 1e8',
        'createConnection',
        { error }
      );
    }

    return {
      client,
      api,
      chainId,
      nativeDecimals: NATIVE_DECIMALS,
      evmDecimals: EVM_DECIMALS,
      nativeToEvmRatio,
    };
  } catch (error) {
    connectionPromise = null;
    wsProvider = null;
    logger.error('Failed to connect to Asset Hub', 'createConnection', { error, rpc });
    throw error;
  }
}

/**
 * Disconnect from Asset Hub and clean up resources.
 */
export async function disconnectAssetHub(): Promise<void> {
  if (!connectionPromise) {
    return;
  }

  try {
    const connection = await connectionPromise;
    connection.client.destroy();
    logger.info('Disconnected from Asset Hub', 'disconnectAssetHub');
  } catch (error) {
    logger.warn('Error during Asset Hub disconnect', 'disconnectAssetHub', { error });
  } finally {
    connectionPromise = null;
    wsProvider = null;
  }
}

// ============================================================
// Balance Utilities
// ============================================================

/**
 * Convert native balance (10 decimals) to EVM-compatible balance (18 decimals).
 * Required for Revive contract interactions.
 *
 * @param nativeBalance Balance in native format (10 decimals)
 * @returns Balance in EVM format (18 decimals)
 */
export function nativeToEvmBalance(nativeBalance: bigint): bigint {
  // Multiply by 10^8 to convert from 10 to 18 decimals
  return nativeBalance * 10n ** BigInt(EVM_DECIMALS - NATIVE_DECIMALS);
}

/**
 * Convert an EVM-18-decimal contract amount to the native-planck value the
 * `Revive.call` extrinsic actually moves, using the chain's NativeToEthRatio.
 *
 * The Revive `value` field is the NATIVE balance (planck, 10 decimals on Asset
 * Hub), NOT the 18-decimal EVM units used inside the contract's `msg.value`
 * comparison. Dividing the EVM amount by the ratio recovers the native planck.
 *
 * @param evmAmount Amount in EVM format (18 decimals)
 * @param ratio NativeToEthRatio from {@link AssetHubConnection.nativeToEvmRatio}
 * @returns Native value in planck (10 decimals)
 */
export function nativeValueFromEvmAmount(evmAmount: bigint, ratio: bigint): bigint {
  if (ratio <= 0n) {
    return evmAmount / 10n ** BigInt(EVM_DECIMALS - NATIVE_DECIMALS);
  }
  return evmAmount / ratio;
}

/**
 * Convert pUSD amount (6 decimals) to EVM format (18 decimals).
 * pUSD uses 6 decimals like USDC/USDT.
 *
 * @param pusdAmount Amount in pUSD format (6 decimals)
 * @returns Amount in EVM format (18 decimals)
 */
export function pusdToEvmAmount(pusdAmount: bigint): bigint {
  const pusdDecimals = CHAIN_CONFIG.pusd.decimals;
  return pusdAmount * 10n ** BigInt(EVM_DECIMALS - pusdDecimals);
}

// ============================================================
// Cleanup
// ============================================================

/**
 * Clean up all Asset Hub resources.
 * Call this when the application is shutting down.
 */
export async function cleanup(): Promise<void> {
  await disconnectAssetHub();
}

// Handle browser unload
if (typeof window !== 'undefined') {
  window.addEventListener('beforeunload', () => {
    void cleanup();
  });
}
